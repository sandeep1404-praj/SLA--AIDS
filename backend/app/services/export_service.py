"""
Export Service — ContentFlow AI
Generates JSON, CSV, and Markdown exports of calendars.
"""

import csv
import io
import json
from datetime import datetime, timedelta


def _safe_csv_field(value) -> str:
    if value is None:
        return ""
    if isinstance(value, list):
        return " | ".join(str(v) for v in value)
    return str(value)


def export_json(calendar: dict, posts: list) -> dict:
    """Return structured JSON export of the calendar and all posts."""
    return {
        "export_version": "1.0",
        "exported_at": datetime.utcnow().isoformat() + "Z",
        "calendar": {
            "id": calendar.get("id") or str(calendar.get("_id", "")),
            "title": calendar.get("title"),
            "start_date": calendar.get("start_date"),
            "duration_days": calendar.get("duration_days", 7),
            "selected_platforms": calendar.get("selected_platforms", []),
            "target_audience": calendar.get("target_audience"),
            "tone": calendar.get("tone"),
            "content_objective": calendar.get("content_objective"),
            "weekly_plan": calendar.get("weekly_plan", []),
        },
        "posts": posts,
    }


def export_csv(calendar: dict, posts: list) -> str:
    """Return CSV string with all posts."""
    output = io.StringIO()
    fieldnames = [
        "date",
        "day_number",
        "platform",
        "theme",
        "content_angle",
        "title",
        "post_text",
        "hashtags",
        "call_to_action",
        "visual_suggestion",
        "word_count",
        "character_count",
        "validation_status",
        "status",
    ]
    writer = csv.DictWriter(
        output, fieldnames=fieldnames, quoting=csv.QUOTE_ALL, extrasaction="ignore"
    )
    writer.writeheader()

    start_date_str = calendar.get("start_date", "")
    try:
        start_date = datetime.fromisoformat(start_date_str)
    except Exception:
        start_date = datetime.utcnow()

    # Build a day→theme map from weekly plan
    day_themes = {}
    for day in calendar.get("weekly_plan", []):
        day_themes[day.get("day_number")] = day.get("theme", "")

    for post in posts:
        day_num = post.get("day_number", 1)
        post_date = start_date + timedelta(days=day_num - 1)
        row = {
            "date": post_date.strftime("%Y-%m-%d"),
            "day_number": day_num,
            "platform": post.get("platform", ""),
            "theme": day_themes.get(day_num, ""),
            "content_angle": _safe_csv_field(post.get("content_angle")),
            "title": _safe_csv_field(post.get("title")),
            "post_text": _safe_csv_field(post.get("post_text")),
            "hashtags": _safe_csv_field(post.get("hashtags")),
            "call_to_action": _safe_csv_field(post.get("call_to_action")),
            "visual_suggestion": _safe_csv_field(post.get("visual_suggestion")),
            "word_count": post.get("word_count", 0),
            "character_count": post.get("character_count", 0),
            "validation_status": post.get("validation_status", ""),
            "status": post.get("status", ""),
        }
        writer.writerow(row)

    return output.getvalue()


def export_markdown(calendar: dict, posts: list) -> str:
    """Return Markdown document grouped by day and platform."""
    lines = []
    title = calendar.get("title", "Content Calendar")
    start_date_str = calendar.get("start_date", "")
    try:
        start_date = datetime.fromisoformat(start_date_str)
    except Exception:
        start_date = datetime.utcnow()

    lines.append(f"# {title}")
    lines.append(f"\n**Generated by ContentFlow AI** | Start Date: {start_date.strftime('%B %d, %Y')}")
    lines.append(f"\n**Platforms:** {', '.join(calendar.get('selected_platforms', []))}")
    lines.append(f"**Tone:** {calendar.get('tone', '')} | **Objective:** {calendar.get('content_objective', '')}")
    lines.append(f"**Target Audience:** {calendar.get('target_audience', '')}")
    lines.append("\n---\n")

    # Group posts by day
    day_posts: dict[int, list] = {}
    for post in posts:
        dn = post.get("day_number", 1)
        day_posts.setdefault(dn, []).append(post)

    # Weekly plan themes
    day_themes = {}
    day_angles = {}
    for day in calendar.get("weekly_plan", []):
        dn = day.get("day_number")
        day_themes[dn] = day.get("theme", "")
        day_angles[dn] = day.get("content_angle", "")

    for day_num in sorted(day_posts.keys()):
        post_date = start_date + timedelta(days=day_num - 1)
        theme = day_themes.get(day_num, "")
        angle = day_angles.get(day_num, "")

        lines.append(f"## Day {day_num} — {post_date.strftime('%A, %B %d')}")
        if theme:
            lines.append(f"**Theme:** {theme}")
        if angle:
            lines.append(f"**Angle:** {angle}")
        lines.append("")

        for post in day_posts[day_num]:
            platform = post.get("platform", "").upper().replace("_", " ")
            lines.append(f"### {platform}")

            if post.get("title"):
                lines.append(f"**{post['title']}**\n")

            lines.append(post.get("post_text", ""))

            if post.get("hashtags"):
                lines.append("\n" + " ".join(post["hashtags"]))

            if post.get("call_to_action"):
                lines.append(f"\n📣 **CTA:** {post['call_to_action']}")

            if post.get("visual_suggestion"):
                lines.append(f"\n🖼️ **Visual:** {post['visual_suggestion']}")

            val = post.get("validation_status", "")
            warnings = post.get("validation_warnings", [])
            if val == "warning" and warnings:
                lines.append(f"\n⚠️ **Validation:** {'; '.join(warnings)}")

            lines.append(f"\n*{post.get('word_count', 0)} words · {post.get('character_count', 0)} chars · Status: {post.get('status', 'draft')}*")
            lines.append("\n---")

        lines.append("")

    return "\n".join(lines)
